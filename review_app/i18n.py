"""Lightweight UI internationalization: English (default) + Hebrew.

Web UI only - the generated video's text stays data-driven (itinerary/place
names). Strings are keyed; Jinja templates call `t('key')` and JS calls
`window.t('key')` (the current-language table is emitted into the page). Language
is a per-browser choice stored in the `lang` cookie and flipped by the globe
toggle (GET /lang/{code}); it is deliberately NOT an app setting - settings.json
is app-global and survives New-trip, whereas language is a viewer preference.

Adding a language = add its code to LANGS and a table to TRANSLATIONS. Missing
keys fall back to English, then to the key itself, so a partial translation
never blanks the UI.
"""

