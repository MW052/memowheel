TRANSLATIONS = {"en": _EN, "he": _HE}


def get_lang(request) -> str:
    """The viewer's language from the `lang` cookie, validated; English default."""
    lang = request.cookies.get("lang", DEFAULT_LANG)
    return lang if lang in LANGS else DEFAULT_LANG


def translator(lang: str):
    """Returns t(key, default=None, **kwargs): looks the key up in `lang`, then
    English, then `default`, then the key itself; formats {placeholders} from
    kwargs (a bad format string never raises - it returns the raw text)."""
    table = TRANSLATIONS.get(lang, _EN)

    def t(key, default=None, **kwargs):
        s = table.get(key) or _EN.get(key) or default or key
        if kwargs:
            try:
                s = s.format(**kwargs)
            except (KeyError, IndexError, ValueError):
                pass
        return s

    return t


def merged_table(lang: str) -> dict:
    """English overlaid by `lang` - the full lookup table emitted to JS so
    window.t() resolves every key (English fallback included)."""
    return {**_EN, **TRANSLATIONS.get(lang, {})}


def i18n_context(request) -> dict:
    """Jinja2 context processor: injects the translator, language, direction, the
    language list, and the JS lookup table into every TemplateResponse."""
    lang = get_lang(request)
    return {
        "t": translator(lang),
        "lang": lang,
        "lang_dir": LANGS[lang]["dir"],
        "LANGS": LANGS,
        "i18n_json": json.dumps(merged_table(lang), ensure_ascii=False),
    }
